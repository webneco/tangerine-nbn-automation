const FULL_TYPES = new Set(Object.values(PAF_STREET_TYPES));

/**
 * Resolve a street type given as an abbreviation or full name (any case)
 * to its full uppercase PAF form. Unknown inputs are returned uppercased.
 */
export function resolveStreetType(input: string | undefined | null): string {
  const key = String(input ?? '').trim().toUpperCase().replace(/\.$/, '').replace(/\s+/g, ' ');
  if (!key) return '';
  if (FULL_TYPES.has(key)) return key;
  return PAF_STREET_TYPES[key] ?? key;
}

/** True if the token is a known PAF abbreviation or full street type. */
export function isStreetTypeToken(token: string): boolean {
  const t = token.toUpperCase();
  return t in PAF_STREET_TYPES || FULL_TYPES.has(t);
}
